import difflib
import subprocess
from pathlib import Path
from datetime import datetime
from typing import Tuple
from config import Config
from logger import SyncLogger


class ConflictResolver:
    def __init__(self, config: Config, logger: SyncLogger):
        self.config = config
        self.logger = logger

    def generate_diff(self, file1: Path, file2: Path) -> str:
        """Generate unified diff between two files."""
        if not file1.exists() or not file2.exists():
            return ""
        
        with open(file1, 'r', encoding='utf-8', errors='ignore') as f:
            lines1 = f.readlines()
        
        with open(file2, 'r', encoding='utf-8', errors='ignore') as f:
            lines2 = f.readlines()
        
        diff = difflib.unified_diff(
            lines1,
            lines2,
            fromfile=str(file1),
            tofile=str(file2),
            lineterm=''
        )
        
        return ''.join(diff)

    def create_conflict_file(self, conflicting_files: list[Path]) -> Path:
        """Create a conflict file with highlighted differences."""
        if not conflicting_files:
            raise ValueError("No conflicting files provided")
            
        base_file = conflicting_files[0]
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        conflict_name = f"conflict_{base_file.name}_{timestamp}.md"
        conflict_path = self.config.conflict_dir / conflict_name
        
        # Get modification times and names
        file_info = []
        for f in conflicting_files:
            mtime = datetime.fromtimestamp(f.stat().st_mtime).strftime("%Y-%m-%d %H:%M:%S")
            file_info.append(f"- **{f.parent.name} version**: `{f}` (modified: {mtime})")
            
        # Generate diffs relative to the first file
        diffs_content = ""
        for i in range(1, len(conflicting_files)):
            other_file = conflicting_files[i]
            diff = self.generate_diff(base_file, other_file)
            diffs_content += f"\n### Diff: {base_file.parent.name} vs {other_file.parent.name}\n```diff\n{diff}\n```\n"
        
        # Create conflict file content
        content = f"""# CONFLICT: {base_file.name}
# Timestamp: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Conflicting Versions
{chr(10).join(file_info)}

## Differences
{diffs_content}

## Resolution Instructions

1. Review the differences above
2. Decide which version to keep or merge manually
3. Edit the original file in any directory with your resolution
4. The sync agent will automatically propagate your changes

---

*This file was automatically generated by the sync agent. You can delete it after resolving the conflict.*
"""
        
        try:
            with open(conflict_path, 'w', encoding='utf-8') as f:
                f.write(content)
            return conflict_path
        except Exception as e:
            self.logger.log_error(f"Failed to create conflict file: {str(e)}", {
                'files': [str(f) for f in conflicting_files]
            })
            raise

    def resolve_conflict(self, conflicting_files: list[Path]) -> bool:
        """Handle conflict by creating conflict file and opening editor."""
        try:
            if not conflicting_files:
                return True
                
            base_file = conflicting_files[0]
            for f in conflicting_files[1:]:
                self.logger.log_conflict(base_file, base_file, f)
            
            # Create conflict file
            conflict_path = self.create_conflict_file(conflicting_files)
            
            # Open in default editor if configured
            if self.config.conflict_auto_open_editor:
                self.open_in_editor(conflict_path)
            
            return True
        except Exception as e:
            self.logger.log_error(f"Conflict resolution failed: {str(e)}", {
                'files': [str(f) for f in conflicting_files]
            })
            return False

    def open_in_editor(self, file_path: Path):
        """Open file in default editor."""
        try:
            if file_path.exists():
                subprocess.Popen(['start', '', str(file_path)], shell=True)
        except Exception as e:
            self.logger.log_error(f"Failed to open editor: {str(e)}", {
                'file': str(file_path)
            })
